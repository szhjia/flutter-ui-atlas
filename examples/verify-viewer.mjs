import {chromium,expect} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
import {join} from 'node:path';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1600,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
const evidence=process.env.ATLAS_EVIDENCE_DIR??'.runtime';
await mkdir(evidence,{recursive:true});
try {
  const url=process.argv[2]??'http://127.0.0.1:60200';
  await page.goto(url);
  const manifestResponse=await page.request.get(new URL('/generated/manifest.json',url).href);
  expect(manifestResponse.ok()).toBe(true);
  const manifest=await manifestResponse.json();
  expect(manifest.screens).toHaveLength(4);
  expect(manifest.screens.every(screen=>screen.status==='captured')).toBe(true);
  expect(manifest.edges).toHaveLength(3);
  expect(manifest.edges.every(edge=>edge.status==='observed')).toBe(true);
  expect(manifest.runtimeErrors).toEqual([]);
  await expect(page.locator('.map-card')).toHaveCount(4);
  await expect.poll(()=>page.locator('.map-card img').evaluateAll(images=>images.every(i=>i.complete&&i.naturalWidth>0))).toBe(true);
  await page.locator('.map-card').first().click();
  await expect(page.locator('.map-relation')).toHaveCount(1);
  await page.getByRole('button',{name:'实时操作',exact:true}).click();
  const frame=page.frameLocator('iframe');
  const open=frame.getByRole('button',{name:'进入示例',exact:true});
  const enable=frame.locator('flt-semantics-placeholder').and(frame.getByRole('button',{name:'Enable accessibility',exact:true}));
  await expect(open.or(enable).first()).toBeVisible();
  if(!await open.isVisible()&&await enable.isVisible())await enable.dispatchEvent('click');
  await open.click();
  await expect(frame.getByRole('button',{name:'查看详情',exact:true})).toBeVisible();
  await page.waitForTimeout(500);
  await page.screenshot({path:join(evidence,'standalone-live.png')});
  await page.getByRole('button',{name:'采集截图',exact:true}).click();
  await page.getByRole('button',{name:'关闭页面详情'}).click();
  await page.getByRole('button',{name:'查看全貌',exact:true}).click();
  await page.waitForTimeout(400);
  await page.screenshot({path:join(evidence,'standalone-map.png')});
  expect(errors).toEqual([]);
  await writeFile(join(evidence,'viewer-result.json'),JSON.stringify({verifiedAt:new Date().toISOString(),captureId:manifest.captureId,screens:4,edges:3,liveNavigation:true,errors},null,2));
  console.log('独立画布、截图、连线详情与真实 Flutter 预览验证通过');
}finally{await browser.close();}
